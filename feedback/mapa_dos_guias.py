"""Build the guide map from the guides folder and flag INVISIBLE documents.

Lists the highest version of every document (name_vNN.md) and warns about guides that no "reading
document" cites. Reading documents are the files every session must read: core (nucleo_*), opening
(00_*), package checklists (pacote_*), tool index and modules. A guide nobody cites is invisible: it
exists but no session will ever open it.
Only READS guides; only WRITES mapa_de_guias_vNN.md (never overwrites).

Usage:
  python feedback/mapa_dos_guias.py            short summary (<= 25 lines)
  python feedback/mapa_dos_guias.py --gravar   write the next version of the map
Env: GUIDES_DIR (default "docs")
"""

from __future__ import annotations

import datetime
import os
import re
import sys

ROOT = os.environ.get("GUIDES_DIR", "docs")
READING_PREFIXES = ("nucleo_", "00_", "pacote_")
IGNORE = re.compile(r"(auditoria_|_resumo|_proposta|_fonte_|^README\.md$)", re.I)


def version_key(name: str) -> tuple[str, int]:
    base = name[:-3]
    found = re.findall(r"_v(\d+)", base)
    return re.sub(r"_v\d+", "", base), int(found[-1]) if found else 0


def newest_per_folder() -> dict[str, list[str]]:
    result: dict[str, list[str]] = {}
    for folder, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in ("antigas",) and not d.startswith("_lixo")]
        best: dict[str, tuple[int, str]] = {}
        for f in files:
            if not f.endswith(".md"):
                continue
            key, v = version_key(f)
            if key not in best or v > best[key][0]:
                best[key] = (v, f)
        if best:
            result[os.path.relpath(folder, ROOT)] = sorted(x[1] for x in best.values())
    return result


def first_line(path: str) -> str:
    with open(path, encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            line = line.strip().lstrip("#").strip()
            if line:
                return line[:110]
    return ""


def main() -> None:
    docs = newest_per_folder()
    reading_text = ""
    for folder, files in docs.items():
        for f in files:
            if f.startswith(READING_PREFIXES):
                with open(os.path.join(ROOT, folder, f), encoding="utf-8", errors="ignore") as fh:
                    reading_text += fh.read()
    orphans = []
    for folder, files in docs.items():
        for f in files:
            if f.startswith(READING_PREFIXES) or IGNORE.search(f) or f.startswith("mapa_de_guias"):
                continue
            if re.sub(r"_v\d+\.md$", "", f).replace(".md", "") not in reading_text:
                orphans.append(os.path.join(folder, f))
    today = datetime.date.today().strftime("%Y-%m-%d")
    out = [
        f"# Guide map | generated by mapa_dos_guias.py on {today}",
        "Highest version of each document. Do not edit by hand: run the script again.",
        "",
    ]
    if orphans:
        out.append(f"## Invisible: {len(orphans)} document(s) no reading document cites")
        out += [f"- `{o}`" for o in orphans]
        out.append("")
    for folder, files in sorted(docs.items()):
        out += [f"## {folder} ({len(files)})", "| file | first line |", "|---|---|"]
        for f in files:
            out.append(f"| `{f}` | {first_line(os.path.join(ROOT, folder, f)).replace('|', '/')} |")
        out.append("")
    print(f"mapa_dos_guias {today}: " + ", ".join(f"{k} {len(v)}" for k, v in sorted(docs.items())))
    print(f"invisible: {len(orphans)}")
    for o in orphans[:15]:
        print("  -", o)
    if "--gravar" in sys.argv:
        taken = [version_key(f)[1] for fs in docs.values() for f in fs if f.startswith("mapa_de_guias")]
        n = max(taken + [0]) + 1
        path = os.path.join(ROOT, f"mapa_de_guias_v{n:02d}.md")
        with open(path, "x", encoding="utf-8") as fh:
            fh.write("\n".join(out) + "\n")
        print("written:", path)


if __name__ == "__main__":
    main()
